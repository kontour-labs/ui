#!/usr/bin/env python3
"""Writes `CldrPlurals.kt` from the Unicode CLDR's plural rules.

    python3 docs/pull-cldr-plurals.py

A language's plural categories — English's one and other, Arabic's six, Japanese's
single other — are what lets a sentence with a number in it be translated at
all: "1 stop", "2 stops", and in Polish "2 przystanki" but "5 przystanków". The
rules are data, published by CLDR in a small expression language, and this
copies them into the library verbatim so every platform answers the same way:
Android's ICU, iOS's Foundation, the browser's `Intl` and the JDK would each
give an answer, from four different CLDR versions.

The rules are kept as CLDR writes them and read at run time by
`PluralRules.kt`, which is the one thing that has to be right about them and is
tested against the samples CLDR publishes alongside each rule. Keeping the text
rather than compiling each rule to Kotlin keeps this file honest: it is the
data, as published, with nothing lost in a translation step.

Pinned to one CLDR release (see `CLDR_VERSION`), so the file only changes when
someone decides it should. Like `pull-device-corners.py`, it is run by hand
and its output is checked in.
"""
from __future__ import annotations

import json
import urllib.request
from pathlib import Path

CLDR_VERSION = "45.0.0"
SOURCE = f"https://cdn.jsdelivr.net/npm/cldr-core@{CLDR_VERSION}/supplemental/plurals.json"
OUT = Path("ui/src/commonMain/kotlin/io/kontour/ui/locale/CldrPlurals.kt")

ORDER = ["zero", "one", "two", "few", "many", "other"]


def main() -> None:
    with urllib.request.urlopen(SOURCE, timeout=30) as response:
        data = json.load(response)
    rules = data["supplemental"]["plurals-type-cardinal"]

    lines = []
    for language in sorted(rules):
        categories = rules[language]
        entries = []
        for category in ORDER:
            rule = categories.get(f"pluralRule-count-{category}")
            if rule is None or category == "other":
                continue
            entries.append(f'"{category}" to "{kotlin_string(rule)}"')
        lines.append(f'    "{language}" to listOf({", ".join(entries)}),')

    OUT.write_text(
        "package io.kontour.ui.locale\n"
        "\n"
        "// Generated by docs/pull-cldr-plurals.py from CLDR "
        f"{CLDR_VERSION}. Do not edit; rerun the script.\n"
        "\n"
        "/**\n"
        " * CLDR's cardinal plural rules, by language, as CLDR writes them.\n"
        " *\n"
        " * Each language lists its categories other than `other`, in CLDR's order,\n"
        " * each with its rule and the samples CLDR publishes after `@integer` and\n"
        " * `@decimal`. `other` is whatever none of them matched. Read by\n"
        " * [PluralRules]; the samples are what `CldrPluralsTest` checks it against.\n"
        " */\n"
        "internal val CldrPluralRules: Map<String, List<Pair<String, String>>> = mapOf(\n"
        + "\n".join(lines)
        + "\n)\n"
    )
    print(f"{OUT}: {len(rules)} languages from CLDR {CLDR_VERSION}")


def kotlin_string(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


if __name__ == "__main__":
    main()
